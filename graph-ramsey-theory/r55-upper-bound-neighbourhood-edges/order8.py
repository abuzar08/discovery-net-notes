"""The order-8 row, sized: how many actions survive the orbit bound.

researcher-1, `r55-42-automorphism-census`: *"order 8 is no better, which kills
the obvious escape. Excluding every group of order 8 would bound the Sylow
2-subgroup by 4 and so bound a -- which nothing does today"*, and it measured
**one** Z_2^3 action (five regular orbits and one of size 2, 126 pair orbits,
15 of 15 cubes timing out).

That is a probe, not an enumeration.  This file does the enumeration, which is
this seat's job: for each of the five groups of order 8, every faithful action
on 42 points, filtered by the orbit lemma.

WHAT THE ORBIT LEMMA GIVES HERE.  For any orbit O of H,

    |Fix(H)| <= R(5-w,5) - 1 + R(5,5-a) - 1,   w, a the clique and
                                               independence numbers of F[O],

maximised over the H-invariant graphs on O that can occur in a (5,5)-graph.
Evaluated per orbit size and per induced group:

    orbit size 2                     37
    orbit size 4 (cyclic or Klein)   26, and 22 after the global count
    orbit size 8, cyclic             17
    orbit size 8, Z_2^3 regular      13

so the bound depends on *which* group acts on the orbit, not only on its size.
An action is kept only if its fixed-point count respects the minimum over all
its orbits.

    python3 order8.py
"""
